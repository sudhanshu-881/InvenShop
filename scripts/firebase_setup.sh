# Create Firebase rules
cat > firestore.rules << 'EOF'
rules_version = '2';
service cloud.firestore {
  match /databases/{database}/documents {
    // Allow users to read/write their own data
    match /users/{userId} {
      allow read, write: if request.auth != null && request.auth.uid == userId;
    }
    
    // Allow shop owners to read/write their shop data
    match /shops/{shopId} {
      allow read, write: if request.auth != null && 
        resource.data.ownerId == request.auth.uid;
    }
    
    // Allow shop staff to read shop data
    match /shops/{shopId} {
      allow read: if request.auth != null && 
        exists(/databases/$(database)/documents/shops/$(shopId)/staff/$(request.auth.uid));
    }
  }
}
EOF

# Create Firebase storage rules
cat > storage.rules << 'EOF'
rules_version = '2';
service firebase.storage {
  match /b/{bucket}/o {
    // Allow users to upload their own files
    match /users/{userId}/{allPaths=**} {
      allow read, write: if request.auth != null && request.auth.uid == userId;
    }
    
    // Allow shop owners to upload shop files
    match /shops/{shopId}/{allPaths=**} {
      allow read, write: if request.auth != null && 
        resource.metadata.ownerId == request.auth.uid;
    }
  }
}
EOF

# Create Firebase functions template
mkdir -p functions
cat > functions/index.js << 'EOF'
const functions = require('firebase-functions');
const admin = require('firebase-admin');

admin.initializeApp();

// Send notification to user
exports.sendNotification = functions.https.onCall(async (data, context) => {
  const { userId, title, body, data: notificationData } = data;
  
  try {
    const message = {
      token: userId, // FCM token
      notification: {
        title: title,
        body: body,
      },
      data: notificationData || {},
    };
    
    const response = await admin.messaging().send(message);
    console.log('Successfully sent message:', response);
    return { success: true, messageId: response };
  } catch (error) {
    console.error('Error sending message:', error);
    return { success: false, error: error.message };
  }
});

// Send notification to topic
exports.sendNotificationToTopic = functions.https.onCall(async (data, context) => {
  const { topic, title, body, data: notificationData } = data;
  
  try {
    const message = {
      topic: topic,
      notification: {
        title: title,
        body: body,
      },
      data: notificationData || {},
    };
    
    const response = await admin.messaging().send(message);
    console.log('Successfully sent message to topic:', response);
    return { success: true, messageId: response };
  } catch (error) {
    console.error('Error sending message to topic:', error);
    return { success: false, error: error.message };
  }
});
EOF

