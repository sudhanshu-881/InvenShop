#!/bin/bash

# InvenShop Firebase Setup Script
# This script helps set up Firebase for InvenShop

set -e

echo "🔥 Starting Firebase Setup for InvenShop..."

# Check if Firebase CLI is installed
if ! command -v firebase &> /dev/null; then
    echo "❌ Firebase CLI not found. Installing..."
    npm install -g firebase-tools
    echo "✅ Firebase CLI installed successfully"
else
    echo "✅ Firebase CLI already installed"
fi

# Check if FlutterFire CLI is installed
if ! command -v flutterfire &> /dev/null; then
    echo "❌ FlutterFire CLI not found. Installing..."
    dart pub global activate flutterfire_cli
    echo "✅ FlutterFire CLI installed successfully"
else
    echo "✅ FlutterFire CLI already installed"
fi

# Login to Firebase
echo "🔐 Logging in to Firebase..."
firebase login

# Initialize Firebase project
echo "🚀 Initializing Firebase project..."
firebase init

# Configure FlutterFire
echo "📱 Configuring FlutterFire..."
flutterfire configure

# Create Firebase configuration files
echo "📄 Creating Firebase configuration files..."

# Create firebase_options.dart
cat > lib/firebase_options.dart << 'EOF'
